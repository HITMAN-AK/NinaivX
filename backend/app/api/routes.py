# ---------- Text in -> spoken reply out (send a reviewed transcript) ----------
@router.post("/chat-voice")
async def chat_voice(
    body: ChatRequest,
    background_tasks: BackgroundTasks,
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    """
    Voice-mode send: the app has already transcribed the user's speech and the user
    confirmed it. This takes the text, runs the agent, and returns the reply text
    plus spoken audio (base64).
    """
    persona = _get_owned_persona(body.persona_id, user, db)
    reply = run_agent(
        db=db, persona_id=persona.id, user_message=body.user_message,
        background_tasks=background_tasks, brief=True,
    )
    audio = await voice_service.text_to_speech(
        text=reply, voice_id=persona.elevenlabs_voice_id or DEFAULT_VOICE_ID,
        model_id=FLASH_TTS_MODEL, language_code=_lang_code(persona.language),
    )
    return {"reply": reply, "audio_base64": base64.b64encode(audio).decode("ascii")}


# ---------- Full voice loop (audio in -> audio out) ----------
@router.post("/voice-chat")
async def voice_chat(
    background_tasks: BackgroundTasks,
    persona_id: str = Form(...),
    file: UploadFile = File(...),
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    """
    The "phone call" loop:
      user's audio  ->  STT (Scribe)  ->  agent  ->  TTS (persona voice)  ->  audio reply
    The transcript is returned in a header so the app can show the captions.
    """
    persona = _get_owned_persona(persona_id, user, db)

    transcript = await voice_service.speech_to_text(file)
    reply = run_agent(
        db=db, persona_id=persona.id, user_message=transcript,
        background_tasks=background_tasks, brief=True,
    )
    audio = await voice_service.text_to_speech(
        text=reply, voice_id=persona.elevenlabs_voice_id or DEFAULT_VOICE_ID,
        model_id=FLASH_TTS_MODEL, language_code=_lang_code(persona.language),
    )
    # Return JSON with the FULL transcript + reply and the audio as base64.
    # (Earlier this used HTTP headers, but those are Latin-1 only and size-limited,
    #  which truncated long replies and broke on em-dashes / non-English text.)
    return {
        "transcript": transcript,
        "reply": reply,
        "audio_base64": base64.b64encode(audio).decode("ascii"),
    }


# ---------- Free synthetic voice samples (for demoing cloning, no real-person data) ----------
_SYNTHETIC_SAMPLE_TEXT = (
    "Hello there. This is a synthetic voice sample created for a demonstration. "
    "I was generated entirely by artificial intelligence, so I am not a real person. "
    "You can use my voice to test how voice cloning works, from start to finish. "
    "The quick brown fox jumps over the lazy dog. Thank you for listening."
)
_synthetic_cache: dict[str, bytes] = {}  # gender -> mp3 bytes (per process)


@router.get("/synthetic-voice")
async def synthetic_voice(gender: str = "male", user: User = Depends(get_current_user)):
    """
    Returns a free, AI-generated voice sample (male or female) as an MP3.
    Because it is synthetic (not a real person), it can be uploaded and cloned to
    demonstrate the cloning feature without any consent, copyright or ethics concerns.
    """
    g = "female" if gender.strip().lower().startswith("f") else "male"
    if g not in _synthetic_cache:
        # Pick an English voice of that gender from the Voice Library (sample text is English).
        matches = await voice_service.list_voices(gender=g, language="en", limit=1)
        voice_id = matches[0]["voice_id"] if matches else DEFAULT_VOICE_ID
        _synthetic_cache[g] = await voice_service.text_to_speech(_SYNTHETIC_SAMPLE_TEXT, voice_id)

    return Response(
        content=_synthetic_cache[g],
        media_type="audio/mpeg",
        headers={"Content-Disposition": f'attachment; filename="synthetic-{g}-voice.mp3"'},
    )


# ---------- Voice management ----------
@router.post("/clone-voice")
async def clone_voice(
    name: str = Form(...),
    description: str = Form(...),
    file: UploadFile = File(...),
    persona_id: str | None = Form(None),
    rights_confirmed: bool = Form(False),
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    """
    Clone a voice from an audio sample. If a persona_id is given, the new
    ElevenLabs voice_id is saved onto that persona, so all future voice replies
    use this cloned voice (e.g. Grandpa Arthur's real voice).

    Consent gate: the caller MUST confirm (rights_confirmed=true) that the recording
    is the intended person's voice and that they have the right to use it. This is
    enforced server-side so it cannot be bypassed by calling the API directly.
    """
    if not rights_confirmed:
        raise HTTPException(
            status_code=400,
            detail="You must confirm you have the right to use this recording before cloning a voice.",
        )

    voice_id = await voice_service.clone_voice(name, description, [file])

    saved_to = None
    if persona_id:
        persona = _get_owned_persona(persona_id, user, db)  # verifies it's the user's persona
        persona.elevenlabs_voice_id = voice_id
        db.commit()
        saved_to = persona.id

    return {
        "message": f"Cloned voice '{name}'.",
        "voice_id": voice_id,
        "saved_to_persona": saved_to,
    }


_PREVIEW_TEXT = "Hi, this is a preview of how I sound. It's lovely to be able to talk with you."


def _preview_line(language: str | None) -> str:
    """
    A short sample sentence to speak in the preview. So the preview is actually heard in
    the persona's language (e.g. Tamil, not English), we generate the line in that
    language; English (the default) uses a fixed line to stay fast. Falls back to the
    English line if anything goes wrong.
    """
    lang = (language or "English").strip()
    if not lang or lang.lower() == "english":
        return _PREVIEW_TEXT
    try:
        from app.services.llm_service import get_llm
        from langchain_core.messages import HumanMessage
        llm = get_llm(model_id=settings.BEDROCK_VOICE_MODEL_ID, max_tokens=80)
        resp = llm.invoke([HumanMessage(content=(
            f"Write ONE short, warm sentence (about 8-15 words) introducing yourself as a voice "
            f"preview, written entirely and naturally in {lang}. No quotes, no emojis, no stage "
            f"directions, no translation or explanation - output only the sentence itself."
        ))])
        text = (resp.content if isinstance(resp.content, str) else str(resp.content)).strip()
        return text or _PREVIEW_TEXT
    except Exception:
        return _PREVIEW_TEXT


@router.get("/preview-voice")
async def preview_voice(
    voice_id: str,
    language: str | None = None,
    user: User = Depends(get_current_user),
):
    """
    Speak a short sample in the given voice so the user can hear it (e.g. right after
    cloning). The sample is spoken in the persona's `language` (e.g. Tamil), not just
    English. Works for any voice_id — a cloned voice or a ready-made one. Returns the
    audio as base64 JSON so the app can play it (no Latin-1 header issues).
    """
    sample = _preview_line(language)
    audio = await voice_service.text_to_speech(
        sample, voice_id, model_id=FLASH_TTS_MODEL, language_code=_lang_code(language)
    )
    return {"audio_base64": base64.b64encode(audio).decode("ascii")}


@router.get("/voices")
async def list_voices(
    gender: str | None = None,
    age: str | None = None,
    language: str | None = None,
    use_case: str | None = "conversational",
    limit: int = 5,
    user: User = Depends(get_current_user),
):
    """
    Search the ElevenLabs **Voice Library** (many languages), filtered by preference.

    - gender:   "male" or "female"
    - age:      "young", "middle_aged" or "old"
    - language: ISO code such as "en", "ta", "hi", "es", "ar", "ja"
    - use_case: defaults to "conversational" (best fit for a talking persona)
    - limit:    how many to return (default 5)

    All filters are optional and applied by ElevenLabs server-side. Each voice
    includes a preview_url so the app can let the user hear it before choosing.
    """
    voices = await voice_service.list_voices(
        gender=gender, age=age, language=language, use_case=use_case, limit=limit
    )
    return {
        "count": len(voices),
        "filters": {"gender": gender, "age": age, "language": language, "use_case": use_case},
        "available_voices": voices,
    }
