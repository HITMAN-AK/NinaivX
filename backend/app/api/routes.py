router = APIRouter(prefix="/api", tags=["NinaivX API"])

DEFAULT_VOICE_ID = "pNInz6obpgDQGcFmaJgB"  # ElevenLabs "Adam" fallback
FLASH_TTS_MODEL = "eleven_flash_v2_5"       # lowest-latency model for live voice calls

# Minimum age to create an account. Set to 18 so the study involves only adults who
# can give their own informed consent — this keeps research ethics approval simple
# (no parental/guardian consent or safeguarding of minors required).
MIN_SIGNUP_AGE = 18

# ---- Strict input-validation limits (enforced server-side on every request) ----
MAX_HUMAN_AGE = 120          # sanity ceiling for any age
MIN_PASSWORD_LEN = 8         # minimum account password length
MIN_PERSONALITY_LEN = 10     # a persona needs a meaningful personality description
PERSONA_AGE_MIN = 1          # a persona's age must be a real positive number
# Simple, dependency-free email check (Supabase does the authoritative validation).
_EMAIL_RE = re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$")

# Map a persona's language name to an ISO code, used to lock TTS pronunciation
# (so e.g. Tamil doesn't drift toward Hindi). Unknown languages fall back to auto-detect.
LANGUAGE_CODES = {
    "english": "en", "tamil": "ta", "hindi": "hi", "telugu": "te", "malayalam": "ml",
    "kannada": "kn", "spanish": "es", "french": "fr", "german": "de", "arabic": "ar",
    "mandarin": "zh", "chinese": "zh", "japanese": "ja", "korean": "ko", "portuguese": "pt",
}

def _lang_code(name: str | None) -> str | None:
    return LANGUAGE_CODES.get((name or "").strip().lower())

# AI-transparency disclosure shown by the app at onboarding and as an in-app indicator.
DISCLOSURE_NOTICE = (
    "This is an AI recreation based on the information provided. It is not the real person and "
    "cannot replace them; all replies are generated by artificial intelligence."
)


# ---------- Schemas ----------
class AuthRequest(BaseModel):
    email: str          # validated by Supabase Auth
    password: str

class SignupRequest(BaseModel):
    # One-step account creation: credentials + profile together.
    email: str
    password: str
    name: str
    age: int
    language: str = "English"

    @field_validator("email")
    @classmethod
    def _email_ok(cls, v: str) -> str:
        v = (v or "").strip()
        if not _EMAIL_RE.match(v):
            raise ValueError("Please enter a valid email address.")
        return v

    @field_validator("password")
    @classmethod
    def _password_ok(cls, v: str) -> str:
        if not v or len(v) < MIN_PASSWORD_LEN:
            raise ValueError(f"Password must be at least {MIN_PASSWORD_LEN} characters.")
        return v

    @field_validator("name", "language")
    @classmethod
    def _not_blank(cls, v: str) -> str:
        v = (v or "").strip()
        if not v:
            raise ValueError("This field is required.")
        return v

    @field_validator("age")
    @classmethod
    def _age_ok(cls, v: int) -> int:
        if v is None or v < MIN_SIGNUP_AGE or v > MAX_HUMAN_AGE:
            raise ValueError(f"You must be between {MIN_SIGNUP_AGE} and {MAX_HUMAN_AGE} to create an account.")
        return v

class PersonaCreate(BaseModel):
    persona_type: PersonaType
    name: str
    age: int
    gender: str
    relationship_with_user: str
    personality_text: str
    elevenlabs_voice_id: str          # required: a voice must be chosen before creating a persona
    cause_of_death: str | None = None
    year_of_passing: int | None = None  # legacy only: temporally grounds the persona's knowledge
    language: str | None = None       # e.g. "English", "Tamil"; falls back to the user's
    user_nickname: str | None = None  # what the persona calls the user (e.g. "beta")

    @field_validator("name", "gender", "relationship_with_user", "elevenlabs_voice_id")
    @classmethod
    def _required_text(cls, v: str) -> str:
        v = (v or "").strip()
        if not v:
            raise ValueError("This field is required.")
        return v

    @field_validator("personality_text")
    @classmethod
    def _personality_ok(cls, v: str) -> str:
        v = (v or "").strip()
        if len(v) < MIN_PERSONALITY_LEN:
            raise ValueError(f"Please describe the personality in at least {MIN_PERSONALITY_LEN} characters.")
        return v

    @field_validator("age")
    @classmethod
    def _persona_age_ok(cls, v: int) -> int:
        if v is None or v < PERSONA_AGE_MIN or v > MAX_HUMAN_AGE:
            raise ValueError(f"Age must be a number between {PERSONA_AGE_MIN} and {MAX_HUMAN_AGE}.")
        return v

    @field_validator("cause_of_death", "language", "user_nickname")
    @classmethod
    def _blank_to_none(cls, v: str | None) -> str | None:
        v = (v or "").strip()
        return v or None

    @field_validator("year_of_passing")
    @classmethod
    def _year_ok(cls, v: int | None) -> int | None:
        if v is not None and (v < 1900 or v > 2100):
            raise ValueError("Year of passing must be a valid year (1900-2100).")
        return v

    @model_validator(mode="after")
    def _type_specific_rules(self):
        if self.persona_type == PersonaType.COMPANION:
            # A companion is a living adult friend — must be 18+.
            if self.age < MIN_SIGNUP_AGE:
                raise ValueError(f"A companion persona must be an adult ({MIN_SIGNUP_AGE} or over).")
            # Cause of death / year of passing only apply to a legacy (deceased) persona.
            if self.cause_of_death:
                raise ValueError("Cause of death only applies to a legacy (deceased) persona.")
            if self.year_of_passing:
                raise ValueError("Year of passing only applies to a legacy (deceased) persona.")
        # Legacy (deceased) personas may be any age (a lost child, etc.), so no lower age bound.
        return self

class PersonaUpdate(BaseModel):
    # All optional: only the fields you send get changed (partial update).
    name: str | None = None
    age: int | None = None
    gender: str | None = None
    relationship_with_user: str | None = None
    personality_text: str | None = None
    cause_of_death: str | None = None
    year_of_passing: int | None = None
    elevenlabs_voice_id: str | None = None
    language: str | None = None
    user_nickname: str | None = None

    @field_validator("year_of_passing")
    @classmethod
    def _year_ok(cls, v):
        if v is not None and (v < 1900 or v > 2100):
            raise ValueError("Year of passing must be a valid year (1900-2100).")
        return v

    @field_validator("name", "gender", "relationship_with_user", "elevenlabs_voice_id")
    @classmethod
    def _no_blank_when_sent(cls, v):
        # If the field is sent, it must not be blanked out.
        if v is not None and not str(v).strip():
            raise ValueError("This field cannot be empty.")
        return v.strip() if isinstance(v, str) else v

    @field_validator("personality_text")
    @classmethod
    def _personality_ok(cls, v):
        if v is not None and len(str(v).strip()) < MIN_PERSONALITY_LEN:
            raise ValueError(f"Please describe the personality in at least {MIN_PERSONALITY_LEN} characters.")
        return v.strip() if isinstance(v, str) else v

    @field_validator("age")
    @classmethod
    def _age_ok(cls, v):
        if v is not None and (v < PERSONA_AGE_MIN or v > MAX_HUMAN_AGE):
            raise ValueError(f"Age must be a number between {PERSONA_AGE_MIN} and {MAX_HUMAN_AGE}.")
        return v

