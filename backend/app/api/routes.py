# ---------- Chat (text) ----------
@router.post("/chat")
def chat(
    body: ChatRequest,
    background_tasks: BackgroundTasks,
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    """Text chat. Memory summary is updated in the background for low latency."""
    persona = _get_owned_persona(body.persona_id, user, db)
    try:
        reply = run_agent(
            db=db, persona_id=persona.id, user_message=body.user_message,
            background_tasks=background_tasks,
        )
        return {"reply": reply}
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Agent error: {e}")


