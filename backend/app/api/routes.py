@router.patch("/personas/{persona_id}")
def update_persona(
    persona_id: str,
    body: PersonaUpdate,
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    """
    Partial update: only the fields you send are changed (e.g. just the
    elevenlabs_voice_id, or just the personality_text). persona_type is fixed.
    """
    persona = _get_owned_persona(persona_id, user, db)
    changes = body.model_dump(exclude_unset=True)  # only fields the client actually sent
    # A companion persona must stay an adult (18+); legacy personas may be any age.
    if "age" in changes and persona.persona_type == PersonaType.COMPANION and changes["age"] < MIN_SIGNUP_AGE:
        raise HTTPException(
            status_code=400,
            detail=f"A companion persona must be an adult ({MIN_SIGNUP_AGE} or over).",
        )
    for field, value in changes.items():
        setattr(persona, field, value)
    db.commit()
    db.refresh(persona)
    return {"message": "Persona updated.", "persona": _persona_dict(persona)}


