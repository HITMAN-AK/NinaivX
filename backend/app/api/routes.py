# ---------- Helper ----------
def _get_owned_persona(persona_id: str, user: User, db: Session) -> Persona:
    """Fetch a persona AND verify it belongs to the current user (prevents IDOR)."""
    persona = (
        db.query(Persona)
        .filter(Persona.id == persona_id, Persona.user_id == user.id)
        .first()
    )
    if not persona:
        raise HTTPException(status_code=404, detail="Persona not found or not yours.")
    return persona


# ---------- Auth (public) ----------
# These are thin proxies to Supabase Auth. Passwords are NEVER stored or hashed by
# this backend - Supabase remains the identity provider and owns credentials.
# They exist so the API can be used end-to-end (e.g. from Swagger) without the
# mobile app, and mirror exactly what the React Native client does via the SDK.

def _supabase_auth(path: str, payload: dict) -> dict:
    url = f"{settings.SUPABASE_URL}/auth/v1/{path}"
    headers = {"apikey": settings.SUPABASE_KEY, "Content-Type": "application/json"}
    try:
        r = httpx.post(url, headers=headers, json=payload, timeout=30.0)
    except Exception as e:
        raise HTTPException(status_code=502, detail=f"Could not reach Supabase Auth: {e}")

    data = r.json() if r.content else {}
    if r.status_code >= 400:
        msg = data.get("msg") or data.get("error_description") or data.get("error") or "Authentication failed."
        raise HTTPException(status_code=r.status_code, detail=msg)
    return data


@router.post("/auth/signup", tags=["Auth"])
def signup(body: SignupRequest, db: Session = Depends(get_db)):
    """
    Create an account AND the user's profile in one step.

    Takes email + password (credentials, stored by Supabase) together with the
    profile details (name, age, language, stored here). Returns an access token
    ready to paste into Swagger's "Authorize" button.

    If the Supabase project has "Confirm email" enabled, no token is returned until
    the email is confirmed; the profile is still created so it is ready on first login.

    Age restriction: only adults (>= MIN_SIGNUP_AGE) may register, so the project
    involves no minors — keeping research ethics approval straightforward. This
    (and all other input validation) is enforced by SignupRequest's validators,
    which reject invalid input with a 422 before this function runs.
    """
    data = _supabase_auth("signup", {"email": body.email, "password": body.password})
    uid = (data.get("user") or {}).get("id")
    access_token = data.get("access_token")

    if not uid:
        raise HTTPException(status_code=502, detail="Supabase did not return a user id.")

    # Create the profile row (id == Supabase Auth UUID). Idempotent if it already exists.
    if not db.query(User).filter(User.id == uid).first():
        db.add(User(id=uid, name=body.name, age=body.age, language=body.language))
        db.commit()

    return {
        "message": "Account and profile created." if access_token else
                   "Account and profile created, but email confirmation is required before logging in.",
        "email_confirmation_required": access_token is None,
        "access_token": access_token,
        "user_id": uid,
        "next_step": "Click Authorize with this token, then create a persona (POST /api/personas)."
                     if access_token else "Confirm the email, then POST /api/auth/login.",
    }


@router.post("/auth/login", tags=["Auth"])
def login(body: AuthRequest):
    """
    Log in with email + password and receive a Supabase access token.
    Paste the returned access_token into the Swagger "Authorize" button.
    """
    data = _supabase_auth("token?grant_type=password", {"email": body.email, "password": body.password})
    return {
        "access_token": data.get("access_token"),
        "refresh_token": data.get("refresh_token"),
        "token_type": data.get("token_type", "bearer"),
        "expires_in": data.get("expires_in"),
        "user_id": (data.get("user") or {}).get("id"),
        "next_step": "Click Authorize in Swagger and paste the access_token.",
    }


